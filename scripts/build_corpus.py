def load_originals(documents: list[dict]) -> list[dict]:
    """按 id 前缀筛出手写文档，保证重复运行时不会累积上一次生成的文档。"""
    originals = [document for document in documents if document["id"].startswith("g_")]
    if len(originals) != 6:
        raise ValueError("guides.json 里应有 6 篇 id 以 g_ 开头的手写文档，实际是 {} 篇".format(len(originals)))
    return originals


def compose_text(rng: random.Random, domain: dict, name: str, keyword: str, detail: str) -> str:
    """拼出一段 40–200 字左右的正文，长度和句子组合都随种子变化。"""
    parts = [rng.choice(ENTITY_TEMPLATES).format(name=name, keyword=keyword, detail=detail)]
    # 一成文档只写 45 字上下，其余 60–175 字起步，让长度分布不那么均匀。
    short = rng.random() < 0.10
    target = 45 if short else rng.randint(60, 175)
    limit = 3 if short else 6
    pool = list(domain["shared"])
    rng.shuffle(pool)
    for sentence in pool:
        if len("".join(parts)) >= target or len(parts) >= limit:
            break
        parts.append(sentence)
    text = "".join(parts)
    # 只有已经足够长的文档才补"雨天"句，避免短文档同时命中"雨天"和"室内"而压过 g_rain。
    if domain.get("rain_shared") and len(text) >= 130 and rng.random() < 0.35:
        parts.append(rng.choice(domain["rain_shared"]))
    if rng.random() < 0.5:
        parts.append(rng.choice(PUBLIC_SENTENCES))
    text = "".join(parts)
    while len(text) > 205 and len(parts) > 2:
        parts.pop()
        text = "".join(parts)
    return text


def build_documents(rng: random.Random, originals: list[dict]) -> tuple[list[dict], dict]:
    """生成全部文档，并返回 关键词 -> 文档 id 的映射，供标注查询使用。"""
    documents = list(originals)
    keyword_to_id = {}
    serial = 0
    for domain in DOMAINS:
        for name, keyword, detail in domain["scenes"]:
            serial += 1
            if keyword in keyword_to_id:
                raise ValueError("关键词重复，无法唯一标注：{}".format(keyword))
            doc_id = "d{:04d}".format(serial)
            keyword_to_id[keyword] = doc_id
            documents.append({
                "id": doc_id,
                "title": name + rng.choice(domain["suffixes"]),
                "text": compose_text(rng, domain, name, keyword, detail),
            })
    return documents, keyword_to_id


def build_cases(keyword_to_id: dict, document_ids: set) -> list[dict]:
    """把关键词标签翻译成文档 id，生成三条难度不同的查询和手写文档查询。"""
    cases = []
    for query, keywords in KEYWORD_QUERIES:
        for keyword in keywords:
            if keyword not in query:
                raise ValueError("明确关键词型查询应包含关键词：{}".format(query))
        cases.append((query, keywords))
    for query, keywords in COLLOQUIAL_QUERIES:
        for keyword in keywords:
            if keyword in query:
                raise ValueError("口语化查询不应包含原关键词：{} / {}".format(query, keyword))
        cases.append((query, keywords))
    for query, keywords in MIXED_QUERIES:
        cases.append((query, keywords))

    labeled = []
    for query, keywords in cases:
        relevant = []
        for keyword in keywords:
            if keyword.startswith("g_"):
                if keyword not in document_ids:
                    raise ValueError("手写文档 id 不存在：{}".format(keyword))
                doc_id = keyword
            elif keyword in keyword_to_id:
                doc_id = keyword_to_id[keyword]
            else:
                raise ValueError("查询引用了未知关键词：{}".format(keyword))
            if doc_id not in relevant:
                relevant.append(doc_id)
        labeled.append({"query": query, "relevant": relevant})
    for query, ids in ORIGINAL_QUERIES:
        labeled.append({"query": query, "relevant": list(ids)})

    return [{"id": "q{:03d}".format(number), "query": item["query"], "relevant": item["relevant"]}
            for number, item in enumerate(labeled, 1)]


def main() -> None:
    existing = json.loads(GUIDES_PATH.read_text(encoding="utf-8"))
    originals = load_originals(existing)
    rng = random.Random(SEED)
    documents, keyword_to_id = build_documents(rng, originals)
    cases = build_cases(keyword_to_id, {document["id"] for document in documents})

    # 保护既有回归测试：手写文档 g_rain 必须仍是"雨天 + 室内"里最短最匹配的一篇。
    for document in documents[6:]:
        content = document["title"] + document["text"]
        if "雨天室内" in content:
            raise ValueError("生成文档不应包含连续的“雨天室内”：{}".format(document["id"]))
        if "雨天" in content and "室内" in content and len(content) < 130:
            raise ValueError("过短的文档同时包含“雨天”和“室内”：{}".format(document["id"]))

    GUIDES_PATH.write_text(json.dumps(documents, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    CASES_PATH.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    lengths = [len(document["text"]) for document in documents[6:]]
    print("语料已写入 {}：{} 篇（手写 6 篇 + 生成 {} 篇）".format(
        GUIDES_PATH.name, len(documents), len(documents) - 6))
    print("生成正文长度：最短 {} 字，最长 {} 字，平均 {:.1f} 字".format(
        min(lengths), max(lengths), sum(lengths) / len(lengths)))
    print("查询已写入 {}：{} 条（关键词 {} / 口语 {} / 混合 {} / 手写文档 {}）".format(
        CASES_PATH.name, len(cases), len(KEYWORD_QUERIES), len(COLLOQUIAL_QUERIES),
        len(MIXED_QUERIES), len(ORIGINAL_QUERIES)))


if __name__ == "__main__":
    main()
